// Minimal DOM stub to actually execute the replay logic for every sample.
// Run from the directory holding flight_replay_script.js:  node test_replay_render.js
const fs = require('fs');
const src = fs.readFileSync('flight_replay_script.js', 'utf8');
const ctxStub = new Proxy({}, {get: () => () => {}, set: () => true});

function el() {
  return {
    style: {}, classList: {toggle() {}, add() {}, remove() {}}, textContent: '',
    value: 0, width: 700, height: 150,
    clientHeight: 210, clientWidth: 700,
    getBoundingClientRect: () => ({width: 700, height: 150, left: 0, top: 0,
                                   right: 700, bottom: 150}),
    getContext: () => ctxStub, addEventListener() {}, onclick: null, oninput: null
  };
}

const store = {};
global.document = {getElementById: id => (store[id] = store[id] || el()),
                   body: {}, querySelector: () => null};
global.getComputedStyle = () => ({getPropertyValue: () => ''});
global.performance = {now: () => 0};
global.window = {addEventListener() {}, removeEventListener() {}, devicePixelRatio: 1};
let frames = 0;
global.requestAnimationFrame = cb => { frames++; if (frames < 5000) cb(frames * 16); };

// eval is intentional and safe here: src is the replay script generated by
// gen_replay.py from this repo's own data, executed against the DOM stub above so
// the real rendering logic runs. There is no external or user-supplied input.
eval(src);

// walk the whole flight through the scrubber handler
const scrub = store['scrub'];
let errors = 0, seen = new Set();
for (let v = 0; v <= 1000; v += 5) {
  try { scrub.oninput({target: {value: v}}); seen.add(store['r_t'].textContent); }
  catch (e) { errors++; if (errors < 3) console.log('ERR at', v, e.message); }
}
console.log('scrub sweep values rendered:', seen.size, 'errors:', errors);
console.log('final readouts -> t:', store['r_t'].textContent,
            'alt:', store['r_alt'].textContent, 'descent:', store['r_des'].textContent,
            'temp:', store['r_temp'].textContent, 'RH:', store['r_hum'].textContent,
            'phase:', store['r_phase'].textContent);
// exercise the play loop to the end of the flight
store['play'].onclick();
console.log('play frames requested:', frames,
            '| button now:', JSON.stringify(store['play'].textContent),
            '| t:', store['r_t'].textContent);
if (errors > 0) { console.log('FAILED'); process.exit(1); }
if (seen.size < 100) { console.log('FAILED: too few distinct positions'); process.exit(1); }
if (!/Replay/.test(store['play'].textContent)) {
  console.log('FAILED: playback did not reach the end of the flight'); process.exit(1);
}
console.log('PASS');
